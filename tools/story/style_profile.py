"""Step 3: measure Lovecraft's style so writers (human or model) can aim at it.

    python tools/story/style_profile.py

Compares word frequencies in the filtered training corpus against everyday
English (the `wordfreq` package) to find his signature vocabulary, and measures
sentence length and punctuation habits. Writes data/style_profile.json (used by
score.py) and STYLE_PROFILE.md (for people).
"""
from __future__ import annotations

import json
import math
import re
import statistics
from collections import Counter

from wordfreq import word_frequency

from common import load_config, repo_path

WORD = re.compile(r"[a-z]+(?:-[a-z]+)*")
SENT = re.compile(r"(?<=[.!?])[”\"’]?\s+(?=[“\"‘A-Z])")


def main():
    cfg = load_config()
    data = repo_path(cfg["dataset_dir"])
    texts = []
    seen = set()
    with open(data / "train.jsonl", encoding="utf-8") as f:
        for line in f:
            t = json.loads(line)["text"]
            if t not in seen:  # ignore oversampling duplicates
                seen.add(t)
                texts.append(t)
    corpus = "\n\n".join(texts)
    words = WORD.findall(corpus.lower())
    counts = Counter(words)
    total = len(words)
    # Words usually capitalised in the corpus are names (Kadath, Akeley): list separately.
    caps = Counter(w.lower() for w in re.findall(r"\b[A-Z][a-z]+(?:-[A-Za-z]+)*", corpus))
    is_name = lambda w: caps[w] > counts[w] * 0.5

    signature, names = [], []
    for w, n in counts.items():
        if n < 8 or len(w) < 4:
            continue
        if is_name(w):
            names.append((n, w))
            continue
        base = word_frequency(w, "en") or 1e-8
        ratio = (n / total) / base
        signature.append((math.log2(ratio), w, n))
    signature.sort(reverse=True)
    top = [{"word": w, "count": n, "log2_ratio": round(r, 2)} for r, w, n in signature[:200]]

    sentences = [s for s in SENT.split(corpus) if len(s.split()) > 2]
    lengths = [len(s.split()) for s in sentences]
    per_k = lambda ch: round(corpus.count(ch) / total * 1000, 2)
    profile = {
        "words": total,
        "sentence_words_mean": round(statistics.mean(lengths), 1),
        "sentence_words_median": statistics.median(lengths),
        "sentences_over_40_words_pct": round(sum(l > 40 for l in lengths) / len(lengths) * 100, 1),
        "semicolons_per_1k_words": per_k(";"),
        "dashes_per_1k_words": per_k("—"),
        "exclamations_per_1k_words": per_k("!"),
        "signature_words": top,
        "names": [w for _, w in sorted(names, reverse=True)[:150]],
        # rate of the top-100 signature words per 1,000 words, for density scoring
        "signature_rate_per_1k": round(
            sum(counts[t["word"]] for t in top[:100]) / total * 1000, 2),
    }
    (data / "style_profile.json").write_text(json.dumps(profile, indent=2), encoding="utf-8")

    md = [
        "# Lovecraft Style Profile",
        "",
        "Generated by `style_profile.py` from the *filtered* training corpus "
        f"({total:,} words). Use it as a checklist when writing or editing STORY.md.",
        "",
        "## Rhythm",
        "",
        f"- Average sentence: **{profile['sentence_words_mean']} words** "
        f"(median {profile['sentence_words_median']}); "
        f"{profile['sentences_over_40_words_pct']}% of sentences run past 40 words.",
        f"- Semicolons: **{profile['semicolons_per_1k_words']} per 1,000 words**. "
        f"Dashes: {profile['dashes_per_1k_words']}. Exclamations: {profile['exclamations_per_1k_words']}.",
        f"- Signature-word density: {profile['signature_rate_per_1k']} of the top-100 words per 1,000 words. "
        "Going far above this reads as parody.",
        "",
        "## Signature vocabulary",
        "",
        "Words he uses far more often than everyday English (log₂ ratio, count).",
        "",
        ", ".join(f"*{t['word']}* ({t['count']})" for t in top[:150]),
        "",
        "## Most frequent names and places",
        "",
        ", ".join(w.capitalize() for w in profile["names"][:100]),
        "",
    ]
    (repo_path("tools/story") / "STYLE_PROFILE.md").write_text("\n".join(md), encoding="utf-8")
    print(json.dumps({k: v for k, v in profile.items() if k not in ("signature_words", "names")}, indent=2))
    print("signature:", ", ".join(t["word"] for t in top[:120]))


if __name__ == "__main__":
    main()
